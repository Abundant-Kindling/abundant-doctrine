#!/usr/bin/env bash
# Functions here are called through check and trap, which shellcheck cannot see.
# shellcheck disable=SC2317,SC2329
# Tests for install.sh and uninstall.sh.
#
#   bash tests/install.test.sh
#
# Every case runs against a fresh config dir from mktemp, with HOME pointed at
# a fake home inside the same temp tree and tests/stubs first on PATH, so the
# stub claude and gh shadow the real ones. Nothing here touches a real config.
# The kit is copied to a path containing a space, so every case also proves
# the installer copes with one.
set -u

repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)
stubs="$repo/tests/stubs"
PATH="$stubs:$PATH"
export PATH

WORK=$(mktemp -d)
WORK=$(cd "$WORK" && pwd -P)
cleanup() { find "$WORK" -delete 2>/dev/null; }
trap cleanup EXIT

HOME="$WORK/home"
mkdir -p "$HOME"
export HOME
unset CLAUDE_CONFIG_DIR

fails=0
ok() { echo "ok - $1"; }
notok() { echo "not ok - $1"; fails=$((fails + 1)); }
check() { # check DESCRIPTION COMMAND...
  local desc=$1
  shift
  if "$@"; then ok "$desc"; else notok "$desc"; fi
}

# Safety: refuse to run at all unless the stubs shadow the real tools.
if [ "$(command -v claude)" != "$stubs/claude" ] || [ "$(command -v gh)" != "$stubs/gh" ]; then
  echo "not ok - stub claude/gh are not first on PATH; refusing to run"
  exit 1
fi
ok "stub claude and gh shadow the real ones"

# The kit, copied to a path with a space in it.
kit="$WORK/my kit/abundant-doctrine"
mkdir -p "$kit"
for f in install.sh uninstall.sh settings.fragment.json CLAUDE.md commands hooks; do
  cp -R "$repo/$f" "$kit/" 2>/dev/null || { echo "not ok - kit copy: $f missing"; exit 1; }
done

n=0
new_cfg() { # fresh config dir and stub log; sets CFG and STUB_LOG
  n=$((n + 1))
  CFG="$WORK/cfg$n"
  mkdir -p "$CFG"
  STUB_LOG="$WORK/stub$n.log"
  : > "$STUB_LOG"
  export STUB_LOG
}
install() { CLAUDE_CONFIG_DIR="$CFG" bash "$kit/install.sh" > "$WORK/out" 2>&1; }
uninstall() { CLAUDE_CONFIG_DIR="$CFG" bash "$kit/uninstall.sh" > "$WORK/out" 2>&1; }
nbackups() { find "$1" -maxdepth 1 -name 'backup-*' | wc -l | tr -d ' '; }
line() { sed -n "$2p" "$1"; }
kit_cmd() { printf 'node "%s/abundant-doctrine/hooks/careful.js"' "$1"; }
count_kit_hooks() { jq --arg c "$(kit_cmd "$1")" '[.hooks.PreToolUse[]?.hooks[]? | select(.command == $c)] | length' "$1/settings.json"; }
marker='<!-- abundant-doctrine: generated by install.sh -->'
# ls -l, not stat: stat -c is GNU-only and stat -f is BSD-only.
# shellcheck disable=SC2012
mode() { ls -l "$1" | cut -c1-10; }

# ---- clean config ----------------------------------------------------------
new_cfg
check "clean: install exits 0" install
check "clean: CLAUDE.md is a regular file, not a link" test -f "$CFG/CLAUDE.md" -a ! -L "$CFG/CLAUDE.md"
check "clean: stub line 1 is the marker" test "$(line "$CFG/CLAUDE.md" 1)" = "$marker"
check "clean: stub imports the kit doctrine" test "$(line "$CFG/CLAUDE.md" 2)" = "@$CFG/abundant-doctrine/CLAUDE.md"
check "clean: stub imports personal.md" test "$(line "$CFG/CLAUDE.md" 3)" = "@$CFG/personal.md"
check "clean: abundant-doctrine links to the kit" test "$(readlink "$CFG/abundant-doctrine")" = "$kit"
check "clean: commands/wrap.md is a link" test -L "$CFG/commands/wrap.md"
check "clean: wrap.md links through abundant-doctrine" test "$(readlink "$CFG/commands/wrap.md")" = "$CFG/abundant-doctrine/commands/wrap.md"
check "clean: wrap.md resolves to the kit's file" cmp -s "$CFG/commands/wrap.md" "$kit/commands/wrap.md"
check "clean: stub's doctrine import resolves to the kit's file" cmp -s "$CFG/abundant-doctrine/CLAUDE.md" "$kit/CLAUDE.md"
check "clean: personal.md exists" test -f "$CFG/personal.md"
check "clean: settings has the Bash hook" test "$(jq -r --arg c "$(kit_cmd "$CFG")" '[.hooks.PreToolUse[] | select(.matcher == "Bash") | .hooks[] | select(.command == $c)] | length' "$CFG/settings.json")" = 1
check "clean: settings has the Supabase hook" test "$(jq -r --arg c "$(kit_cmd "$CFG")" '[.hooks.PreToolUse[] | select(.matcher == "mcp__.*[Ss]upabase.*__(execute_sql|apply_migration)") | .hooks[] | select(.command == $c)] | length' "$CFG/settings.json")" = 1
for p in superpowers supabase vercel; do
  check "clean: $p enabled in settings" test "$(jq -r --arg k "$p@claude-plugins-official" '.enabledPlugins[$k]' "$CFG/settings.json")" = true
  check "clean: claude plugin install $p called" grep -qx "plugin install $p@claude-plugins-official" "$STUB_LOG"
done
check "clean: no backup dir (nothing to back up)" test "$(nbackups "$CFG")" = 0
check "clean: output points at the README" grep -q README "$WORK/out"

# The hook command as written in settings.json, run as Claude Code would run it.
hook=$(jq -r '.hooks.PreToolUse[] | select(.matcher == "Bash") | .hooks[0].command' "$CFG/settings.json")
printf '%s' '{"tool_input":{"command":"git push --force origin main"}}' > "$WORK/blocked.json"
printf '%s' '{"tool_input":{"command":"git status"}}' > "$WORK/allowed.json"
sh -c "$hook" < "$WORK/blocked.json" > /dev/null 2>&1
check "hook: command from settings.json blocks a force-push (exit 2)" test $? = 2
sh -c "$hook" < "$WORK/allowed.json" > /dev/null 2>&1
check "hook: command from settings.json allows git status (exit 0)" test $? = 0

# ---- second run is a no-op -------------------------------------------------
cp "$CFG/settings.json" "$WORK/settings.first"
cp "$CFG/CLAUDE.md" "$WORK/claude.first"
check "rerun: install exits 0" install
check "rerun: settings.json byte-identical" cmp -s "$CFG/settings.json" "$WORK/settings.first"
check "rerun: CLAUDE.md byte-identical" cmp -s "$CFG/CLAUDE.md" "$WORK/claude.first"
check "rerun: no backup dir" test "$(nbackups "$CFG")" = 0

# ---- existing CLAUDE.md of her own -----------------------------------------
new_cfg
printf 'MY RULES\n' > "$CFG/CLAUDE.md"
check "own CLAUDE.md: install exits 0" install
check "own CLAUDE.md: one backup dir" test "$(nbackups "$CFG")" = 1
check "own CLAUDE.md: backup holds MY RULES" grep -q 'MY RULES' "$CFG"/backup-*/CLAUDE.md
check "own CLAUDE.md: personal.md holds MY RULES" grep -q 'MY RULES' "$CFG/personal.md"
check "own CLAUDE.md: CLAUDE.md is now the stub" test "$(line "$CFG/CLAUDE.md" 1)" = "$marker"
check "own CLAUDE.md: rerun exits 0" install
check "own CLAUDE.md: rerun makes no second backup" test "$(nbackups "$CFG")" = 1
check "own CLAUDE.md: rerun does not duplicate MY RULES" test "$(grep -c 'MY RULES' "$CFG/personal.md")" = 1

# ... and a personal.md already there: appended, not replaced
new_cfg
printf 'MY RULES\n' > "$CFG/CLAUDE.md"
printf 'OLD PERSONAL\n' > "$CFG/personal.md"
check "own CLAUDE.md + personal.md: install exits 0" install
check "own CLAUDE.md + personal.md: old personal kept" grep -q 'OLD PERSONAL' "$CFG/personal.md"
check "own CLAUDE.md + personal.md: MY RULES appended" grep -q 'MY RULES' "$CFG/personal.md"
check "own CLAUDE.md + personal.md: personal.md backed up" grep -q 'OLD PERSONAL' "$CFG"/backup-*/personal.md

# ... and a CLAUDE.md that is a link to a file of hers: the file is not touched
new_cfg
printf 'LINKED RULES\n' > "$WORK/her-dotfile.md"
ln -s "$WORK/her-dotfile.md" "$CFG/CLAUDE.md"
check "linked CLAUDE.md: install exits 0" install
check "linked CLAUDE.md: her linked file unchanged" test "$(cat "$WORK/her-dotfile.md")" = "LINKED RULES"
check "linked CLAUDE.md: personal.md holds its text" grep -q 'LINKED RULES' "$CFG/personal.md"
check "linked CLAUDE.md: CLAUDE.md is now the stub file" test -f "$CFG/CLAUDE.md" -a ! -L "$CFG/CLAUDE.md"

# ---- existing real commands/wrap.md ----------------------------------------
new_cfg
mkdir -p "$CFG/commands"
printf 'MY WRAP\n' > "$CFG/commands/wrap.md"
check "own wrap.md: install exits 0" install
check "own wrap.md: backed up" grep -q 'MY WRAP' "$CFG"/backup-*/commands/wrap.md
check "own wrap.md: replaced by the link" test -L "$CFG/commands/wrap.md"

# ---- existing settings.json with her own hook ------------------------------
new_cfg
cat > "$CFG/settings.json" <<'JSON'
{
  "model": "opus",
  "hooks": {
    "PreToolUse": [
      { "matcher": "Bash", "hooks": [ { "type": "command", "command": "echo her-own-hook" } ] }
    ]
  }
}
JSON
chmod 600 "$CFG/settings.json"
check "own settings: install exits 0" install
check "own settings: install keeps mode 600" test "$(mode "$CFG/settings.json")" = "-rw-------"
check "own settings: model kept" test "$(jq -r .model "$CFG/settings.json")" = opus
check "own settings: her hook kept" test "$(jq '[.hooks.PreToolUse[].hooks[] | select(.command == "echo her-own-hook")] | length' "$CFG/settings.json")" = 1
check "own settings: her hook still first" test "$(jq -r '.hooks.PreToolUse[0].hooks[0].command' "$CFG/settings.json")" = "echo her-own-hook"
check "own settings: kit hooks appended (two)" test "$(count_kit_hooks "$CFG")" = 2
check "own settings: settings.json backed up" grep -q her-own-hook "$CFG"/backup-*/settings.json
check "own settings: backup keeps mode 600" test "$(mode "$CFG"/backup-*/settings.json)" = "-rw-------"
check "own settings: rerun exits 0" install
check "own settings: kit hooks still two after rerun" test "$(count_kit_hooks "$CFG")" = 2
check "own settings: rerun makes no second backup" test "$(nbackups "$CFG")" = 1

# ---- uninstall -------------------------------------------------------------
cp "$CFG/settings.json" "$WORK/settings.pre-uninstall"
check "uninstall: exits 0" uninstall
check "uninstall: made a new backup dir" test "$(nbackups "$CFG")" = 2
newest=$(find "$CFG" -maxdepth 1 -name 'backup-*' | sort | tail -n 1)
check "uninstall: backup holds settings.json as it was" cmp -s "$newest/settings.json" "$WORK/settings.pre-uninstall"
check "uninstall: unedited stub not backed up" test ! -e "$newest/CLAUDE.md"
check "uninstall: keeps mode 600" test "$(mode "$CFG/settings.json")" = "-rw-------"
check "uninstall: CLAUDE.md stub removed" test ! -e "$CFG/CLAUDE.md"
check "uninstall: abundant-doctrine link removed" test ! -L "$CFG/abundant-doctrine"
check "uninstall: wrap.md link removed" test ! -L "$CFG/commands/wrap.md"
check "uninstall: kit hooks removed" test "$(count_kit_hooks "$CFG")" = 0
check "uninstall: kit plugins removed" test "$(jq '[(.enabledPlugins // {}) | keys[] | select(endswith("@claude-plugins-official"))] | length' "$CFG/settings.json")" = 0
check "uninstall: her hook kept" test "$(jq '[.hooks.PreToolUse[].hooks[] | select(.command == "echo her-own-hook")] | length' "$CFG/settings.json")" = 1
check "uninstall: model kept" test "$(jq -r .model "$CFG/settings.json")" = opus
check "uninstall: personal.md kept" test -f "$CFG/personal.md"
check "uninstall: kit itself untouched" test -f "$kit/install.sh"
newest=$(find "$CFG" -maxdepth 1 -name 'backup-*' | sort | tail -n 1)
oldest=$(find "$CFG" -maxdepth 1 -name 'backup-*' | sort | head -n 1)
check "uninstall: backup keeps mode 600" test "$(mode "$newest/settings.json")" = "-rw-------"
check "uninstall: points at the oldest backup as the pre-install files" \
  grep -qF "Your oldest backup, $oldest, holds your files as they were before the kit was installed" "$WORK/out"
check "uninstall: names its own backup as what it just saved" \
  grep -qF "What uninstall just saved, before removing or rewriting it: $newest." "$WORK/out"
# shellcheck disable=SC2016 # expanded by the inner sh, not here
check "uninstall: does not call its own backup the oldest" \
  sh -c '! grep -qF "Your oldest backup, $1," "$2"' _ "$newest" "$WORK/out"

# an edited stub is backed up before removal
new_cfg
check "edited stub: install exits 0" install
printf 'MY EXTRA LINE\n' >> "$CFG/CLAUDE.md"
check "edited stub: uninstall exits 0" uninstall
check "edited stub: stub removed" test ! -e "$CFG/CLAUDE.md"
check "edited stub: her line survives in the backup" grep -q 'MY EXTRA LINE' "$CFG"/backup-*/CLAUDE.md
check "edited stub: uninstall says where" grep -q 'backup-.*/CLAUDE.md' "$WORK/out"
# shellcheck disable=SC2016 # expanded by the inner sh, not here
check "edited stub: its only backup is named as just saved, not as the oldest" \
  sh -c 'grep -q "What uninstall just saved" "$1" && ! grep -q "Your oldest backup" "$1"' _ "$WORK/out"

# uninstall leaves files it did not make
new_cfg
printf 'MY RULES\n' > "$CFG/CLAUDE.md"
mkdir -p "$CFG/commands"
printf 'MY WRAP\n' > "$CFG/commands/wrap.md"
ln -s "$WORK" "$CFG/abundant-doctrine"
check "uninstall foreign: exits 0" uninstall
check "uninstall foreign: her CLAUDE.md kept" grep -q 'MY RULES' "$CFG/CLAUDE.md"
check "uninstall foreign: her wrap.md kept" grep -q 'MY WRAP' "$CFG/commands/wrap.md"
check "uninstall foreign: link to elsewhere kept" test -L "$CFG/abundant-doctrine"

# ---- malformed settings.json -----------------------------------------------
new_cfg
printf '{not json' > "$CFG/settings.json"
install
check "malformed: install exits non-zero" test $? != 0
check "malformed: settings.json unchanged" test "$(cat "$CFG/settings.json")" = '{not json'
check "malformed: no abundant-doctrine link" test ! -e "$CFG/abundant-doctrine" -a ! -L "$CFG/abundant-doctrine"
check "malformed: no CLAUDE.md" test ! -e "$CFG/CLAUDE.md"
check "malformed: no commands dir" test ! -e "$CFG/commands"
check "malformed: no backup dir" test "$(nbackups "$CFG")" = 0
check "malformed: no plugin installs" test ! -s "$STUB_LOG"
check "malformed: message names settings.json" grep -q settings.json "$WORK/out"

# ---- kit moved -------------------------------------------------------------
new_cfg
check "moved: first install exits 0" install
mkdir -p "$WORK/moved kit"
mv "$kit" "$WORK/moved kit/"
kit="$WORK/moved kit/abundant-doctrine"
check "moved: rerun from new path exits 0" install
check "moved: abundant-doctrine points to the new path" test "$(readlink "$CFG/abundant-doctrine")" = "$kit"
check "moved: wrap.md resolves to the moved kit" cmp -s "$CFG/commands/wrap.md" "$kit/commands/wrap.md"
hook=$(jq -r '.hooks.PreToolUse[] | select(.matcher == "Bash") | .hooks[0].command' "$CFG/settings.json")
sh -c "$hook" < "$WORK/blocked.json" > /dev/null 2>&1
check "moved: hook still blocks (exit 2)" test $? = 2

# ---- missing jq ------------------------------------------------------------
# A PATH holding every tool the installer needs except jq.
nojq="$WORK/nojq-bin"
mkdir -p "$nojq"
for t in bash sh git node dirname basename date mkdir ln cp mv cat rm mktemp cmp grep sed tr readlink ls find sort tail head wc; do
  p=$(command -v "$t") && ln -s "$p" "$nojq/$t"
done
ln -s "$stubs/claude" "$nojq/claude"
ln -s "$stubs/gh" "$nojq/gh"
new_cfg
CLAUDE_CONFIG_DIR="$CFG" PATH="$nojq" bash "$kit/install.sh" > "$WORK/out" 2>&1
check "no jq: install exits non-zero" test $? != 0
check "no jq: message says brew install jq" grep -q 'brew install jq' "$WORK/out"
check "no jq: does not blame git" test "$(grep -c 'brew install git' "$WORK/out")" = 0
check "no jq: nothing written" test "$(find "$CFG" | wc -l | tr -d ' ')" = 1

# ---- default config dir is ~/.claude ---------------------------------------
STUB_LOG="$WORK/stub-home.log"
export STUB_LOG
bash "$kit/install.sh" > "$WORK/out" 2>&1
check "default: install with no CLAUDE_CONFIG_DIR exits 0" test $? = 0
check "default: stub imports ~/.claude doctrine" test "$(line "$HOME/.claude/CLAUDE.md" 2)" = "@~/.claude/abundant-doctrine/CLAUDE.md"
check "default: stub imports ~/.claude/personal.md" test "$(line "$HOME/.claude/CLAUDE.md" 3)" = "@~/.claude/personal.md"

# ---- config path with a space is refused -----------------------------------
CFG="$WORK/cfg with space"
mkdir -p "$CFG"
install
check "spaced config: install exits non-zero" test $? != 0
check "spaced config: nothing written" test "$(find "$CFG" | wc -l | tr -d ' ')" = 1

# ---- config path with a shell metacharacter is refused ---------------------
CFG="$WORK/cfg\$x"
mkdir -p "$CFG"
install
check "dollar in config path: install exits non-zero" test $? != 0
check "dollar in config path: nothing written" test "$(find "$CFG" | wc -l | tr -d ' ')" = 1

echo
if [ "$fails" -eq 0 ]; then
  echo "all install tests pass"
  exit 0
fi
echo "$fails FAILING"
exit 1
