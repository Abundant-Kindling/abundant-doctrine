#!/usr/bin/env bash
# Removes what install.sh added to ${CLAUDE_CONFIG_DIR:-$HOME/.claude}, and
# nothing else.
#
#   bash uninstall.sh
#
# Removes: the generated CLAUDE.md (only if it still carries the install
# marker), the abundant-doctrine and commands/wrap.md links (only if they point
# into this kit), the kit's hooks and its three plugin entries in
# settings.json. Keeps: personal.md, your own hooks and settings, your backups.
# Restores nothing automatically; it prints the oldest backup (your files
# from before the kit) so you can copy back what you want. The plugins stay
# installed in Claude Code.
set -u

kit=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)
marker='<!-- abundant-doctrine: generated by install.sh -->'
marketplace="claude-plugins-official"

die() { echo "uninstall: $*" >&2; exit 1; }

config=${CLAUDE_CONFIG_DIR:-$HOME/.claude}
case "$config" in /*) ;; *) config="$PWD/$config" ;; esac
while [ "${#config}" -gt 1 ] && [ "${config%/}" != "$config" ]; do config=${config%/}; done

link="$config/abundant-doctrine"
stub="$config/CLAUDE.md"
settings="$config/settings.json"
wrap="$config/commands/wrap.md"
hook_cmd="node \"$link/hooks/careful.js\""
if [ "$config" = "$HOME/.claude" ]; then
  # The import text is for Claude Code to expand, not the shell.
  # shellcheck disable=SC2088
  shown="~/.claude"
else
  shown=$config
fi

# Anything removed or rewritten that is not exactly what install.sh made is
# copied here first, the same shape as install.sh's backups.
backup_dir=""
backup() { # backup PATH NAME-INSIDE-BACKUP
  if [ -z "$backup_dir" ]; then
    local base i=1
    base="$config/backup-$(date +%Y%m%d-%H%M%S)"
    backup_dir=$base
    while [ -e "$backup_dir" ]; do i=$((i + 1)); backup_dir="$base-$i"; done
    mkdir -p "$backup_dir" || die "could not create $backup_dir"
  fi
  mkdir -p "$(dirname "$backup_dir/$2")"
  cp -Pp "$1" "$backup_dir/$2" || die "could not back up $1"
}

# Settings first: if they cannot be read, stop before changing anything.
work=$(mktemp -d) || die "could not make a temp directory"
trap 'rm -f "$work"/*; rmdir "$work" 2>/dev/null' EXIT
edit_settings=no
if [ -e "$settings" ]; then
  edit_settings=yes
  command -v jq > /dev/null 2>&1 || die "jq is needed to edit $settings. Install it with: brew install jq"
  if ! jq --arg cmd "$hook_cmd" --arg mp "$marketplace" '
      def strip:
        if type == "object" and (.hooks | type) == "array"
           and any(.hooks[]; type == "object" and .command == $cmd)
        then (.hooks |= map(select((type == "object" and .command == $cmd) | not)))
             | if (.hooks | length) == 0 then empty else . end
        else . end;
      if (.hooks.PreToolUse | type) == "array" then
        .hooks.PreToolUse |= map(strip)
        | if (.hooks.PreToolUse | length) == 0 then del(.hooks.PreToolUse) else . end
        | if (.hooks | length) == 0 then del(.hooks) else . end
      else . end
      | if (.enabledPlugins | type) == "object" then
          .enabledPlugins |= with_entries(select(.key as $k
            | ["superpowers", "supabase", "vercel"] | map(. + "@" + $mp) | index($k) | not))
          | if (.enabledPlugins | length) == 0 then del(.enabledPlugins) else . end
        else . end
    ' "$settings" > "$work/settings.json"; then
    die "$settings is not valid JSON. Nothing was changed."
  fi
fi

if [ -f "$stub" ] && [ ! -L "$stub" ] && [ "$(sed -n 1p "$stub")" = "$marker" ]; then
  printf '%s\n@%s/abundant-doctrine/CLAUDE.md\n@%s/personal.md\n' "$marker" "$shown" "$shown" > "$work/stub.md"
  if ! cmp -s "$stub" "$work/stub.md"; then
    backup "$stub" CLAUDE.md
    echo "Your generated CLAUDE.md had your own edits; saved to $backup_dir/CLAUDE.md."
  fi
  rm -f "$stub" && echo "Removed $stub."
elif [ -e "$stub" ] || [ -L "$stub" ]; then
  echo "Left $stub alone: install.sh did not write it."
fi

if [ -L "$wrap" ]; then
  case "$(readlink "$wrap")" in
    "$link/commands/wrap.md" | "$kit/commands/wrap.md") rm -f "$wrap" && echo "Removed $wrap." ;;
    *) echo "Left $wrap alone: it does not point into the kit." ;;
  esac
elif [ -e "$wrap" ]; then
  echo "Left $wrap alone: it is your own file."
fi

if [ -L "$link" ]; then
  if [ "$(readlink "$link")" = "$kit" ]; then
    rm -f "$link" && echo "Removed $link."
  else
    echo "Left $link alone: it points to $(readlink "$link"), not $kit."
  fi
fi

if [ "$edit_settings" = yes ] && ! cmp -s "$settings" "$work/settings.json"; then
  backup "$settings" settings.json
  # Keep the file's permissions: settings.json can hold tokens.
  if ! { cp -p "$settings" "$settings.abundant-new" \
         && cat "$work/settings.json" > "$settings.abundant-new" \
         && mv -f "$settings.abundant-new" "$settings"; }; then
    die "could not write $settings"
  fi
  echo "Removed the kit's hooks and plugin entries from $settings."
fi

echo
echo "Nothing was restored automatically. Your own rules are still in $config/personal.md;"
echo "to keep loading them, rename that file to CLAUDE.md."
# The oldest backup is the one install.sh made before it first changed
# anything, so it holds your files as they were before the kit. A backup this
# run made is uninstall's own copy of what it just removed or rewrote, and is
# named separately. The names sort by date and time.
oldest=""
for d in "$config"/backup-*; do
  [ -d "$d" ] || continue
  [ "$d" = "$backup_dir" ] && continue
  oldest=$d
  break
done
if [ -n "$oldest" ]; then
  echo "Your oldest backup, $oldest, holds your files as they were before the kit was installed. Copy back from it whatever you want."
fi
if [ -n "$backup_dir" ]; then
  echo "What uninstall just saved, before removing or rewriting it: $backup_dir."
fi
if [ -z "$oldest" ] && [ -z "$backup_dir" ]; then
  echo "There are no backups in $config."
fi
echo "The plugins stay installed. To remove them: claude plugin uninstall <name>@$marketplace"
